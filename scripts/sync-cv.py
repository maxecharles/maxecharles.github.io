#!/usr/bin/env python3
"""Pull the CV from Overleaf and regenerate the content section of cv.html.

Usage (from the repo root):
    python3 scripts/sync-cv.py            # git pull from Overleaf, then rebuild
    python3 scripts/sync-cv.py --no-pull  # rebuild from the local copy only

The Overleaf project is cloned (git-ignored) into cv-source/. Only the part of
cv.html between the CV:START and CV:END markers is replaced.
"""

import html
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT / "cv-source"
TEX_FILE = SOURCE_DIR / "Resume" / "main.tex"
HTML_FILE = ROOT / "cv.html"

START_MARKER = "<!-- CV:START (generated by scripts/sync-cv.py — edit in Overleaf) -->"
END_MARKER = "<!-- CV:END -->"

# Sections in the LaTeX that shouldn't appear on the website: any section whose
# title contains one of these words (case-insensitive), e.g. "References",
# "Referees", "Professional References".
SKIP_SECTIONS = {"reference", "referee"}

# Hover-preview photos, keyed by (title, institution/organisation).
IMAGES = {
    ("Bachelor of Science (Honours)", "University of Sydney"): "images/talk_photos/usyd_grad.jpeg",
    ("Bachelor of Science", "University of Wollongong"): "images/talk_photos/uow_grad.jpeg",
}

ACCENT = '<span style="color: var(--md-accent);">{}</span>'
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


# ---------------------------------------------------------------- LaTeX parsing

def strip_comments(tex):
    """Remove % comments, keeping escaped \\%."""
    return "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in tex.splitlines())


def read_group(s, i):
    """Read a balanced {...} group starting at/after index i. Returns (content, end)."""
    while s[i].isspace():
        i += 1
    if s[i] != "{":
        raise ValueError(f"Expected '{{' at: {s[i:i + 40]!r}")
    depth, start = 0, i
    for j in range(i, len(s)):
        if s[j] == "{" and s[j - 1] != "\\":
            depth += 1
        elif s[j] == "}" and s[j - 1] != "\\":
            depth -= 1
            if depth == 0:
                return s[start + 1:j], j + 1
    raise ValueError("Unbalanced braces")


def read_groups(s, i, n):
    groups = []
    for _ in range(n):
        g, i = read_group(s, i)
        groups.append(g)
    return groups, i


def inline(tex):
    """Convert inline LaTeX markup to HTML."""
    s = " ".join(tex.split())
    s = html.escape(s, quote=False)
    s = s.replace(r"\&amp;", "&amp;").replace(r"\%", "%").replace(r"\,", "&thinsp;")
    s = s.replace(r"\justifying", "").replace("---", "—").replace("--", "–")
    s = re.sub(r"(\d) - ", r"\1 – ", s)  # date ranges
    s = re.sub(r"\\\\", " ", s)

    patterns = [
        (r"\{\\Courier\s*\\fontsize\{[^{}]*\}\{[^{}]*\}\\selectfont\s*([^{}]*)\}", r"<code>\1</code>"),
        (r"\\texttt\{([^{}]*)\}", r"<code>\1</code>"),
        (r"\\href\{([^{}]*)\}\{([^{}]*)\}", r'<a href="\1" target="_blank">\2</a>'),
        (r"\\url\{([^{}]*)\}", r'<a href="\1" target="_blank">\1</a>'),
        (r"\\textbf\{([^{}]*)\}", r"<b>\1</b>"),
        (r"\\(?:textit|emph)\{([^{}]*)\}", r"<i>\1</i>"),
        (r"\\(?:footnotesize|small|textsc|textrm)\{([^{}]*)\}", r"\1"),
        (r"(?<!\\)\{([^{}]*)\}", r"\1"),  # bare grouping braces
    ]
    changed = True
    while changed:
        changed = False
        for pat, rep in patterns:
            s, n = re.subn(pat, rep, s)
            changed |= n > 0
    return s.strip()


def format_date(tex):
    """'2025.11' -> 'Nov 2025'; anything else passes through inline()."""
    m = re.fullmatch(r"\s*(\d{4})\.(\d{2})\s*", tex)
    if m:
        return f"{MONTHS[int(m.group(2)) - 1]} {m.group(1)}"
    return inline(tex)


def parse_sections(tex):
    tex = strip_comments(tex)
    sections, i = [], 0
    while (m := re.compile(r"\\sectionBlock").search(tex, i)):
        (head, body), i = read_groups(tex, m.end(), 2)
        title, _ = read_group(head, head.index(r"\section") + len(r"\section"))
        sections.append((inline(title), body))
    return sections


# ---------------------------------------------------------------- HTML output

def render_heading(section, args):
    title, a2, a3, date = (inline(a) for a in args)
    if section == "Education":
        org, sub = a2, a3  # {degree}{university}{department}{date}
    else:
        org, sub = a3, a2  # {role}{location}{organisation}{date}
    if org.lower().startswith("self"):
        joiner = " · "
    elif org.startswith(("University", "School")):
        joiner = " at the "
    else:
        joiner = " at "
    image = IMAGES.get((title, org))
    attr = f' data-image="{image}"' if image else ""
    return [
        '    <div class="edu-entry">',
        f"      <h3{attr}>{title}{joiner}{ACCENT.format(org)}</h3>",
        f"      <p><i>{sub}</i> ({date})</p>",
    ]


def render_body(section, body):
    out, i, in_entry = [], 0, False
    token = re.compile(r"\\eduHeading|\\itemListStart|\\(pub|award|skill)ListStart")
    while True:
        m = token.search(body, i)
        text = inline(body[i:m.start() if m else len(body)])
        if text:
            out.append(f"    <p>{text}</p>")
        if not m:
            break

        if m.group(0) == r"\eduHeading":
            if in_entry:
                out.append("    </div>\n")
            args, i = read_groups(body, m.end(), 4)
            out += render_heading(section, args)
            in_entry = True

        elif m.group(0) == r"\itemListStart":
            end = body.index(r"\itemListEnd", m.end())
            chunk, j, items = body[m.end():end], 0, []
            while (k := chunk.find(r"\myItem", j)) != -1:
                item, j = read_group(chunk, k + len(r"\myItem"))
                items.append(inline(item))
            indent = "      " if in_entry else "    "
            out.append(f"{indent}<ul>")
            out += [f"{indent}  <li>{it}</li>" for it in items]
            out.append(f"{indent}</ul>")
            i = end + len(r"\itemListEnd")

        else:  # pub / award / skill lists of \item's
            kind = m.group(1)
            end = body.index(rf"\{kind}ListEnd", m.end())
            items = [x for x in re.split(r"\\item\b", body[m.end():end])[1:] if x.strip()]
            if kind == "skill":
                out += [f"    <p>{inline(x)}</p>" for x in items]
            else:
                out.append("    <ul>")
                for x in items:
                    text, _, date = x.partition(r"\hfill")
                    text = inline(text).rstrip(".")
                    date = date.strip().rstrip(".")
                    if date:
                        text += f" ({format_date(date)})"
                    if kind == "award":  # \emph{Award name}: details
                        text = re.sub(r"^<i>(.*?)</i>", r"<b>\1</b>", text)
                    out.append(f"      <li>{text}</li>")
                out.append("    </ul>")
            i = end + len(rf"\{kind}ListEnd")

    if in_entry:
        out.append("    </div>")
    return out


def build_html(tex):
    lines = []
    for title, body in parse_sections(tex):
        if any(word in title.lower() for word in SKIP_SECTIONS):
            continue
        lines.append(f"\n    <h2>{title}</h2>")
        lines += render_body(title, body)
    return "\n".join(lines)


# ---------------------------------------------------------------- main

def main():
    if "--no-pull" not in sys.argv:
        print("Pulling from Overleaf…")
        subprocess.run(["git", "-C", str(SOURCE_DIR), "pull", "--ff-only"], check=True)

    content = build_html(TEX_FILE.read_text())
    leftover = sorted(set(re.findall(r"\\[A-Za-z]+", content)))
    if leftover:
        print(f"Warning: unconverted LaTeX in output: {', '.join(leftover)}"
              " — add a pattern for it in inline().")
    page = HTML_FILE.read_text()
    pattern = re.compile(re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.S)
    if not pattern.search(page):
        sys.exit(f"Couldn't find the CV markers in {HTML_FILE.name}")
    new_page = pattern.sub(lambda _: f"{START_MARKER}{content}\n    {END_MARKER}", page)

    if new_page == page:
        print("cv.html is already up to date.")
    else:
        HTML_FILE.write_text(new_page)
        print("Updated cv.html — review with `git diff cv.html`, then commit and push.")


if __name__ == "__main__":
    main()
